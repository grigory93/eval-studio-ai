"""
Inspect AI Task Definition generated by EvalStudio AI.
Runnable via CLI: inspect eval task.py
"""

from inspect_ai import Task, task
from inspect_ai.dataset import MemoryDataset, Sample
from inspect_ai.scorer import (
    accuracy,
    mean,
    stderr,
)
from app.core.scorers import (
    model_graded_qa_scorer,
    policy_adherence_scorer,
    tool_verification_scorer,
)
from app.core.bridge import adk_agent_solver

# 1. Dataset Samples (1 Categorized Test Cases)
RAW_SAMPLES = [
    {
        "id": "sample-crash-01",
        "input": "Trigger exception",
        "target": "N/A",
        "metadata": {
            "category": "exception",
            "grading_rubric": null,
            "expected_tools": null,
            "difficulty": "medium",
            "policy_rule_id": null,
            "custom_metadata": {}
        }
    }
]

DATASET_SAMPLES = [
    Sample(
        id=s["id"],
        input=s["input"],
        target=s["target"],
        metadata=s["metadata"],
    )
    for s in RAW_SAMPLES
]

DATASET = MemoryDataset(
    samples=DATASET_SAMPLES,
    name="Crash Suite",
    location="memory",
)

# 2. Inspect Task Definition with Multi-Scorers and Fault Tolerance
@task
def test_crash_eval() -> Task:
    return Task(
        dataset=DATASET,
        solver=adk_agent_solver(target_spec="examples/customer_support_adk/agent.py:non_existent_var"),
        scorer=[
            model_graded_qa_scorer(),
            policy_adherence_scorer(),
            tool_verification_scorer(),
        ],
        fail_on_error=False,
        time_limit=60,
        message_limit=10,
    )


if __name__ == "__main__":
    from inspect_ai import eval
    eval(test_crash_eval(), model="google/gemini-2.5-flash")
