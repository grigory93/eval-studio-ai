import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import { CodeViewer } from './CodeViewer';

describe('CodeViewer Component', () => {
  const sampleTaskCode = `"""
Inspect AI Task Definition generated by EvalStudio AI.
"""

from inspect_ai import Task, task
from app.core.bridge import adk_agent_solver

# =====================================================================
# 1. Inspect Task Definition with Multi-Scorers and Fault Tolerance
# =====================================================================
@task
def eval_customer_support() -> Task:
    return Task(
        dataset=get_dataset(),
        solver=adk_agent_solver(target_spec="examples/customer_support_adk/agent.py:root_agent"),
    )

# =====================================================================
# 2. Dataset Loader & Memory Dataset Builder
# =====================================================================
def get_dataset():
    return MemoryDataset(samples=RAW_SAMPLES)

# =====================================================================
# 3. Categorized Test Samples (50 Records)
# =====================================================================
RAW_SAMPLES = [
    {"id": "sample-01", "input": "Hello", "target": "Hi"}
]
`;

  const sampleJson = JSON.stringify(
    [{ id: 'sample-01', input: 'Hello', target: 'Hi', metadata: { category: 'happy_path' } }],
    null,
    2
  );

  beforeEach(() => {
    vi.restoreAllMocks();
  });

  it('renders task.py subtab by default and displays concise task definition', () => {
    render(
      <CodeViewer
        taskCode={sampleTaskCode}
        samplesJson={sampleJson}
        sampleCount={50}
        filename="custom_eval.py"
      />
    );

    expect(screen.getByText('custom_eval.py')).toBeDefined();
    expect(screen.getByText('samples.json')).toBeDefined();
    expect(screen.getByText('50 records')).toBeDefined();

    // Verify concise task definition is shown (shows section 1 and 2, but decouples section 3)
    expect(screen.getByText(/Inspect Task Definition with Multi-Scorers/i)).toBeDefined();
    expect(screen.getByText(/50 Records Decoupled/i)).toBeDefined();
  });

  it('switches to samples.json subtab and renders JSON records', () => {
    render(
      <CodeViewer
        taskCode={sampleTaskCode}
        samplesJson={sampleJson}
        sampleCount={1}
        filename="custom_eval.py"
      />
    );

    const samplesTabBtn = screen.getByRole('button', { name: /samples\.json/i });
    fireEvent.click(samplesTabBtn);

    // Should now display JSON content
    expect(screen.getByText(/"category": "happy_path"/i)).toBeDefined();
    expect(screen.getByRole('button', { name: /Copy JSON/i })).toBeDefined();
    expect(screen.getByRole('button', { name: /Download \.json/i })).toBeDefined();
  });

  it('handles clipboard copy on active subtab', () => {
    const writeTextMock = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', {
      value: { writeText: writeTextMock },
      configurable: true,
      writable: true,
    });

    render(
      <CodeViewer
        taskCode={sampleTaskCode}
        samplesJson={sampleJson}
        sampleCount={1}
        filename="task.py"
      />
    );

    const copyBtn = screen.getByRole('button', { name: /Copy Task Code/i });
    fireEvent.click(copyBtn);

    expect(writeTextMock).toHaveBeenCalled();
  });
});
